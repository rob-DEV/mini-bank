-- No balance column: balances are derived from ledger entries (00003).
CREATE TABLE accounts (
                          id              uuid        PRIMARY KEY,   -- UUIDv7, generated by the service
                          kind            text        NOT NULL CHECK (kind IN ('customer', 'system')),
                          customer_id     uuid        REFERENCES customers (id),
                          account_type    text        NOT NULL CHECK (account_type IN ('current', 'savings', 'internal')),
                          sort_code       char(6),
                          account_number  char(8),
                          currency        char(3)     NOT NULL DEFAULT 'GBP',
                          status          text        NOT NULL DEFAULT 'open'
                              CHECK (status IN ('open', 'frozen', 'closed')),
                          created_at      timestamptz NOT NULL DEFAULT now(),

                          CONSTRAINT currency_format       CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT sort_code_format      CHECK (sort_code ~ '^[0-9]{6}$'),
    CONSTRAINT account_number_format CHECK (account_number ~ '^[0-9]{8}$'),
    CONSTRAINT uk_account_identifier UNIQUE (sort_code, account_number),

    -- Customer accounts must have an owner and bank details; system accounts
    -- (e.g. the funding account opening balances come from) must not.
    CONSTRAINT kind_shape CHECK (
        (kind = 'customer'
            AND customer_id IS NOT NULL
            AND sort_code IS NOT NULL
            AND account_number IS NOT NULL
            AND account_type IN ('current', 'savings'))
        OR
        (kind = 'system'
            AND customer_id IS NULL
            AND sort_code IS NULL
            AND account_number IS NULL
            AND account_type = 'internal')
    )
);

CREATE INDEX accounts_customer_id_idx ON accounts (customer_id);

