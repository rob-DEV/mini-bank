-- +goose Up
-- One row per money movement.
CREATE TABLE transactions (
                              id               uuid        PRIMARY KEY,  -- ours: UUIDv7, generated by the service
                              kind             text        NOT NULL CHECK (kind IN ('transfer', 'opening_balance')),

    -- Idempotency: a key is unique per caller, not globally. A replay hits
    -- uk_idempotency; the store compares request_hash and returns the original.
                              initiated_by     uuid        NOT NULL,
                              idempotency_key  text        NOT NULL CHECK (length(idempotency_key) BETWEEN 1 AND 255),
                              request_hash     bytea       NOT NULL,

                              created_at       timestamptz NOT NULL DEFAULT now(),

                              CONSTRAINT uk_idempotency UNIQUE (initiated_by, idempotency_key)
);

-- Double-entry legs. Signed amounts: debit < 0, credit > 0.
CREATE TABLE entries (
                         id              bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                         transaction_id  uuid        NOT NULL REFERENCES transactions (id),
                         account_id      uuid        NOT NULL REFERENCES ledger_accounts (id),
                         amount_minor    bigint      NOT NULL CHECK (amount_minor <> 0),
                         currency        char(3)     NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX entries_account_idx     ON entries (account_id, id);
CREATE INDEX entries_transaction_idx ON entries (transaction_id);

-- History is immutable: corrections are new, reversing transactions.
-- +goose StatementBegin
CREATE FUNCTION ledger_append_only() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% on % is not allowed: the ledger is append-only', TG_OP, TG_TABLE_NAME;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER transactions_append_only
    BEFORE UPDATE OR DELETE ON transactions
    FOR EACH ROW EXECUTE FUNCTION ledger_append_only();

CREATE TRIGGER entries_append_only
    BEFORE UPDATE OR DELETE ON entries
    FOR EACH ROW EXECUTE FUNCTION ledger_append_only();

CREATE VIEW account_balances AS
SELECT a.id                             AS account_id,
       a.currency,
       COALESCE(sum(e.amount_minor), 0) AS balance_minor
FROM ledger_accounts a
         LEFT JOIN entries e ON e.account_id = a.id
GROUP BY a.id, a.currency;

-- +goose Down
DROP VIEW account_balances;
DROP TABLE entries;
DROP TABLE transactions;
DROP FUNCTION ledger_append_only();